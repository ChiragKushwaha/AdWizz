#!/usr/bin/env python3
"""
Extracts pixel-art sprites from design/image.png into crisp grids:
  app/src/main/java/rocks/chirag/adshield/ui/DesignArt.kt

For each sprite: crop the region, find the pixel-cell size that best fits the art (lowest colour
variance inside cells), sample each cell's centre and snap it to the sprite's palette. Cells that
match the sky background become transparent.

Only generic pieces are taken (bat, heart, snowy owl). The design's boy wizard (round glasses,
scar) and winged golden ball are Harry Potter character/prop designs (Warner Bros. IP) and are
deliberately not extracted.

Run from the repo root:  python3 scripts/extract_design_assets.py   (needs Pillow)
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "design/image.png")
OUT = os.path.join(ROOT, "app/src/main/java/rocks/chirag/adshield/ui/DesignArt.kt")

SPRITES = {
    # name: (crop box in image px, palette char -> RGB)
    "BAT": ((738, 98, 832, 136), {"O": (0x14, 0x12, 0x16), "Y": (0xF2, 0xE2, 0x2E)}),
    "HEART": ((1158, 57, 1214, 104), {"O": (0x1A, 0x10, 0x12), "R": (0xEC, 0x6A, 0x5C), "W": (0xFF, 0xF4, 0xF0)}),
    # White snowy owl (just the owl: cropped above the title letters and the bat it perches on).
    "OWL": ((622, 326, 742, 423), {"O": (0x10, 0x10, 0x12), "W": (0xFA, 0xFA, 0xFA), "G": (0xA4, 0xA4, 0xA8),
                                   "Y": (0xF4, 0xE8, 0x2A)}),
}
BACKGROUND = (0xDD, 0xE3, 0xEB)


def dist(a, b):
    return sum((x - y) ** 2 for x, y in zip(a, b))


def best_cell(img):
    """Cell size (and offset) whose cells are most uniform."""
    w, h = img.size
    px = img.load()
    best = None
    for cell in [c / 2 for c in range(6, 21)]:  # 3.0 .. 10.0 px
        for off in range(0, int(cell)):
            score, n = 0, 0
            y = off + cell / 2
            while y < h:
                x = off + cell / 2
                while x < w:
                    c = px[int(x), int(y)]
                    for dx, dy in ((-cell / 4, 0), (cell / 4, 0), (0, -cell / 4), (0, cell / 4)):
                        xx, yy = int(x + dx), int(y + dy)
                        if 0 <= xx < w and 0 <= yy < h:
                            score += dist(c, px[xx, yy]); n += 1
                    x += cell
                y += cell
            s = score / max(n, 1)
            if best is None or s < best[0]:
                best = (s, cell, off)
    return best[1], best[2]


def extract(box, palette):
    img = Image.open(IMG).convert("RGB").crop(box)
    cell, off = best_cell(img)
    w, h = img.size
    px = img.load()
    rows = []
    y = off + cell / 2
    while y < h:
        row = ""
        x = off + cell / 2
        while x < w:
            c = px[int(x), int(y)]
            choices = [(dist(c, BACKGROUND), ".")] + [(dist(c, rgb), k) for k, rgb in palette.items()]
            row += min(choices)[1]
            x += cell
        rows.append(row)
        y += cell
    rows = outside_transparent(rows)
    # Trim empty borders.
    rows = [r for r in rows if r.strip(".")]
    left = min(len(r) - len(r.lstrip(".")) for r in rows)
    right = max(len(r.rstrip(".")) for r in rows)
    return [r[left:right] for r in rows], cell


def outside_transparent(rows):
    """Cells reachable from the border without crossing the outline are background; light cells
    enclosed by the outline are the sprite's shine (the sky behind the art can be near-white)."""
    g = [list(r) for r in rows]
    h, w = len(g), len(g[0])
    seen, stack = set(), [(x, y) for y in range(h) for x in (0, w - 1)] + [(x, y) for x in range(w) for y in (0, h - 1)]
    while stack:
        x, y = stack.pop()
        if (x, y) in seen or not (0 <= x < w and 0 <= y < h) or g[y][x] == "O":
            continue
        seen.add((x, y))
        if g[y][x] in ".W":
            g[y][x] = "."
            stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    has_shine = any("W" in r for r in rows)
    for y in range(h):
        for x in range(w):
            if (x, y) not in seen and g[y][x] == "." and has_shine:
                g[y][x] = "W"
    return ["".join(r) for r in g]


def main():
    out = ["package rocks.chirag.adshield.ui", "", "import androidx.compose.ui.graphics.Color", "",
           "// GENERATED by scripts/extract_design_assets.py from design/image.png — don't edit by hand.", "",
           "/** Sprites lifted from the AdWizz design. '.' is transparent. */", "object DesignArt {"]
    for name, (box, pal) in SPRITES.items():
        rows, cell = extract(box, pal)
        print(f"{name}: {len(rows[0])}x{len(rows)} cells (cell {cell}px)")
        print("\n".join(rows))
        out.append(f"    val {name} = arrayOf(")
        out += [f'        "{r}",' for r in rows]
        out.append("    )")
        colors = ", ".join(f"'{k}' to Color(0xFF{r:02X}{g:02X}{b:02X})" for k, (r, g, b) in pal.items())
        out.append(f"    val {name}_PALETTE = mapOf({colors})")
        out.append("")
    out.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
